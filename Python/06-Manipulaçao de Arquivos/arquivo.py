# Open abre o arquivo, com seu primeiro argumento 
# sendo para o nome do arquivo e sua extensão, 
# enquanto o segundo argumento é a FORMA que vamos abrir, como nos exemplos abaixo

# Para ler um arquivo
arquivo = open('exemplo.txt', 'r')

# Para escrever em um arquivo
